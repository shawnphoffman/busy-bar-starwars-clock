"""Rasterize digits from the Star Wars fonts into pixel bitmaps for the 72x16 BUSY Bar display.
Writes a TypeScript module (path in argv[1]) and prints an ASCII preview of each font."""
import glob, json, sys
from PIL import Image, ImageDraw, ImageFont

FONT_DIR = "/Users/shawnhoffman/Development/projects/star-wars-fonts/fonts"
MAX_H = 13          # digit rows; leaves 3 px for the AM/PM marker row or breathing room
MAX_W = 66          # "88:88" including colon and gaps must fit in 72 with margins
GAP = 1             # px between glyphs
COLON_W = 3         # colon column incl. gaps, drawn by the app
THRESH = 100
CHARS = '0123456789'

def raster(path, size):
    f = ImageFont.truetype(path, size)
    # common vertical frame for all digits so baselines line up
    l, t, r, b = f.getbbox(CHARS)
    glyphs = {}
    for ch in CHARS:
        cl, ct, cr, cb = f.getbbox(ch)
        w = max(1, cr - cl); h = b - t
        img = Image.new('L', (w + 2, h + 2), 0)
        ImageDraw.Draw(img).text((1 - cl, 1 - t), ch, font=f, fill=255)
        px = img.load()
        rows = [''.join('#' if px[x, y] > THRESH else '.' for x in range(img.width)) for y in range(img.height)]
        # trim empty columns left/right
        cols = [x for x in range(img.width) if any(r[x] == '#' for r in rows)]
        if not cols: cols = [0]
        rows = [r[cols[0]:cols[-1] + 1] for r in rows]
        glyphs[ch] = rows
    return glyphs

def trim_rows(glyphs):
    # drop rows empty in every glyph (top and bottom only), keep shared frame
    n = len(next(iter(glyphs.values())))
    top = 0
    while top < n and all(set(g[top]) <= {'.'} for g in glyphs.values()): top += 1
    bot = n
    while bot > top and all(set(g[bot - 1]) <= {'.'} for g in glyphs.values()): bot -= 1
    return {k: v[top:bot] for k, v in glyphs.items()}

def mean_run(glyphs):
    """Average length of horizontal ink runs across all glyphs: a proxy for stroke weight."""
    runs = []
    for g in glyphs.values():
        for row in g:
            n = 0
            for ch in row + '.':
                if ch == '#': n += 1
                elif n:
                    runs.append(n); n = 0
    return sum(runs) / len(runs) if runs else 0

def dilate(glyphs):
    """Thickens every glyph by one pixel to the right and one down, so 1 px strokes become 2 px."""
    out = {}
    for k, rows in glyphs.items():
        h = len(rows); w = len(rows[0]) + 1
        grid = [['.'] * w for _ in range(h + 1)]
        for y, row in enumerate(rows):
            for x, ch in enumerate(row):
                if ch == '#':
                    grid[y][x] = '#'; grid[y][x + 1] = '#'; grid[y + 1][x] = '#'; grid[y + 1][x + 1] = '#'
        out[k] = [''.join(r) for r in grid]
    return out

THIN = 1.7
# Chosen by eye on the device: these draw with 1 px strokes that get lost on the LED matrix.
THICKEN = {'aldhani', 'ghorelle', 'ninth-vision', 'dixian'}

def fits(glyphs):
    h = len(next(iter(glyphs.values())))
    w = 4 * len(glyphs['8'][0]) + 3 * GAP + COLON_W
    return h <= MAX_H and w <= MAX_W

out = {}
for path in sorted(glob.glob(f'{FONT_DIR}/*/export/*-Regular.ttf')):
    name = path.split('/')[-3]
    best = None
    for size in range(8, 26):
        g = trim_rows(raster(path, size))
        thin = name in THICKEN
        if thin: g = trim_rows(dilate(g))
        if fits(g): best = (size, g, thin)
        else:
            if best: break
    if not best:
        print(f'!! {name}: nothing fits'); continue
    size, g, thin = best
    h = len(g['0'])
    out[name] = {'size': size, 'height': h, 'glyphs': g}
    print(f'== {name} size={size} h={h} thickened={thin} widths={[len(g[c][0]) for c in CHARS]} ==')
    for y in range(h):
        print(' '.join(g[c][y] for c in CHARS))

ts = ['// Generated by genfonts.py from the star-wars-fonts repo. Do not edit by hand.',
      '// Each glyph is a list of rows; "#" is ink, "." is transparent.',
      'export interface PixelFont { readonly name: string; readonly height: number; readonly glyphs: Readonly<Record<string, readonly string[]>> }',
      'export const FONTS: readonly PixelFont[] = [']
for name, d in out.items():
    ts.append(f'  {{ name: {json.dumps(name)}, height: {d["height"]}, glyphs: {json.dumps(d["glyphs"], separators=(",", ":"))} }},')
ts.append('];')
if len(sys.argv) > 1:
    open(sys.argv[1], 'w').write('\n'.join(ts) + '\n')
    print('wrote', sys.argv[1])
